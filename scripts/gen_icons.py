"""Build web/src/shared/iconMap.ts from the icon names used in the data files.

Importing only the icons we use keeps the bundle small (lucide has over a thousand).
Run again after adding an intent with a new icon.
"""
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
EXTRA = ["Mic", "MicOff", "BadgeCheck", "Wifi", "WifiOff", "Languages", "Smile", "ChevronLeft",
         "ChevronRight", "Plus", "Send", "Volume2", "QrCode", "Settings", "Eye", "Circle",
         "Check", "X", "TriangleAlert", "Megaphone", "Armchair", "Clock", "Timer", "UsersRound",
         "ShieldCheck", "LogOut", "Bell", "BellOff", "RefreshCw", "Type", "Loader", "Info",
         "DoorOpen", "Hand", "PlaneTakeoff", "Plane", "Keyboard", "CircleHelp", "Image", "ListChecks"]


def names() -> list[str]:
    found = set(EXTRA)
    for fn in ("intents.yaml", "replies.yaml", "announcements.yaml"):
        for row in yaml.safe_load((ROOT / "data" / "intents" / fn).read_text(encoding="utf-8")):
            found.add(row["icon"])
    return sorted(found)


def main() -> None:
    ns = names()
    lines = ["// Generated by scripts/gen_icons.py. Do not edit by hand.",
             "import type { LucideIcon } from 'lucide-react';",
             "import {"]
    lines += [f"  {n}," for n in ns]
    lines += ["} from 'lucide-react';", "", "export const ICONS: Record<string, LucideIcon> = {"]
    lines += [f"  {n}," for n in ns]
    lines += ["};", ""]
    out = ROOT / "web" / "src" / "shared" / "iconMap.ts"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out} with {len(ns)} icons")
    missing = [n for n in ns if not re.search(rf"\b{n}\b",
               (ROOT / "web/node_modules/lucide-react/dist/lucide-react.d.ts").read_text(encoding="utf-8"))]
    print("missing in installed lucide:", missing)


if __name__ == "__main__":
    main()
